#!/usr/bin/env python3
"""Install global guidance and native defaults with backups. Preview by default."""
import argparse
from datetime import datetime, timezone
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import shlex
import stat
import sys
import tomllib
import uuid

ROOT = Path(__file__).resolve().parents[1]


def load_oas(source):
    spec = importlib.util.spec_from_file_location('oas_setup_source', Path(source) / 'scripts/oas.py')
    module = importlib.util.module_from_spec(spec); spec.loader.exec_module(module)
    return module


oas = load_oas(ROOT)
START, END = oas.MANAGED_START, oas.MANAGED_END
GLOBAL_INSTRUCTIONS = oas.GLOBAL_INSTRUCTIONS
# Rollback actions and the line printed for each.
LABELS = {'restore': 'restore', 'remove': 'remove', 'keep': 'kept (modified since install)', 'absent': 'already absent'}


def managed(original, content):
    block = START + '\n' + content + '\n' + END
    if START in original or END in original:
        if original.count(START) != 1 or original.count(END) != 1 or original.index(START) > original.index(END):
            raise ValueError('Malformed or duplicate managed markers')
        a = original.index(START); b = original.index(END) + len(END)
        return original[:a] + block + original[b:]
    return original + ('\n\n' if original else '') + block + '\n'


def merged(base, overlay):
    if not isinstance(base, dict):
        raise ValueError(f'Refusing to merge settings into a non-object value: {base!r}')
    out = dict(base)
    for k, v in overlay.items():
        out[k] = merged(out.get(k, {}), v) if isinstance(v, dict) else v
    return out


# Owen's compaction trigger, as a share of each runtime's own auto-compact window.
# Only Claude Code and Gemini CLI take a percentage; Codex takes an absolute token
# count, which would mean a different share for every model window.
COMPACT_PERCENT = 35
COMPACTION_HOOK_FILES = ('.claude/settings.json', '.codex/hooks.json')


# Claude Code lists skill descriptions within a budget that is a share of the
# context window (default 0.01) and drops the least-used descriptions first.
# Owen's skills plus plugin skills overflowed the default; a value the user set wins.
SKILL_LISTING_BUDGET = 0.02

# Each workflow is also installed as a Claude Code skill, so bare `claude` and
# desktop sessions load it on demand without the oas launcher. Descriptions name
# the work that should trigger them; unattended is user-invocable only.
WORKFLOW_SKILLS = {
    'development': 'Owen\'s development workflow: scope, criteria, implement, verify, review, and commit a code change in a repository. Use when a task changes, fixes, refactors, reviews, or ships code.',
    'research': 'Owen\'s research workflow: frame the question, trace primary sources, keep a claim ledger with confidence labels, and run logged experiments. Use for literature questions, comparing methods with citations, paper reading, or ML experiments.',
    'ops': 'Owen\'s everyday operations workflow: verify the account, read live calendar, mail, and task state, plan the day, and draft (not send) messages. Use for daily planning, inbox or calendar work, outreach drafts, or recurring personal routines.',
    'tutor': 'Owen\'s tutoring workflow: one question at a time, no solution code, end with a retrieval check. Use for coursework, homework, labs, or exam study.',
    'unattended': 'Owen\'s unattended local job contract: owner, writable scope, limits, checkpoints, and stop rules for a preauthorized bounded job.',
}
WORKFLOW_SKILL_MARKER = '<!-- Generated by owens-agent-system setup'


def workflow_skill(mode, source, description):
    """The SKILL.md that setup installs for one workflow, generated from workflows/<mode>.md."""
    front = [f'name: oas-{mode}', 'description: ' + json.dumps(description)]
    if mode == 'unattended':
        front.append('disable-model-invocation: true')
    body = (Path(source) / f'workflows/{mode}.md').read_text(encoding='utf-8')
    return ('---\n' + '\n'.join(front) + '\n---\n'
            f'{WORKFLOW_SKILL_MARKER} from workflows/{mode}.md; edit the source and rerun setup. -->\n'
            f'Relative paths below are in `{Path(source)}`.\n\n' + body)


def compaction_hook(source):
    return shlex.join([sys.executable, str(Path(source) / 'scripts/oas.py'), 'compact-context'])


def with_hook(config, command):
    """Add the OAS SessionStart compact hook; keep every other hook and replace an older OAS one."""
    if not isinstance(config.get('hooks', {}), dict) or not isinstance(config.get('hooks', {}).get('SessionStart', []), list):
        raise ValueError('Refusing to edit malformed hooks configuration')
    def ours(group):
        handlers = group.get('hooks') if isinstance(group, dict) else None
        return isinstance(handlers, list) and any(
            isinstance(h, dict) and 'oas.py' in str(h.get('command', '')) and str(h.get('command', '')).endswith('compact-context')
            for h in handlers)
    hooks = dict(config.get('hooks', {}))
    groups = [g for g in hooks.get('SessionStart', []) if not ours(g)]
    groups.append({'matcher': 'compact', 'hooks': [{'type': 'command', 'command': command}]})
    hooks['SessionStart'] = groups
    return {**config, 'hooks': hooks}


CODEX_COMPACT_START = '# owens-agent-system:compaction start'
CODEX_COMPACT_END = '# owens-agent-system:compaction end'


def codex_context_window(home, model):
    """The model's context_window from Codex's own model cache, or None when it is not recorded."""
    try:
        cache = json.loads((home / '.codex/models_cache.json').read_text(encoding='utf-8'))
    except (OSError, ValueError):
        return None
    stack = [cache]
    while stack:
        item = stack.pop()
        if isinstance(item, dict):
            if model in (item.get('slug'), item.get('id'), item.get('model'), item.get('name')) and type(item.get('context_window')) is int:
                return item['context_window']
            stack.extend(item.values())
        elif isinstance(item, list):
            stack.extend(item)
    return None


def codex_compaction(old, home):
    """Keep a managed model_auto_compact_token_limit at COMPACT_PERCENT of the configured model's window.

    Codex takes only an absolute token count, so the value is right for the model in
    ~/.codex/config.toml at install time; rerun setup after changing that model.
    """
    a, b = old.find(CODEX_COMPACT_START), old.find(CODEX_COMPACT_END)
    if (a < 0) != (b < 0) or a > b:
        raise ValueError('Malformed OAS compaction block in .codex/config.toml')
    rest = old if a < 0 else old[:a] + old[b + len(CODEX_COMPACT_END):].lstrip('\n')
    try:
        config = tomllib.loads(rest)
    except tomllib.TOMLDecodeError as error:
        raise ValueError(f'Cannot parse .codex/config.toml: {error}') from None
    model = config.get('model')
    window = codex_context_window(home, model) if isinstance(model, str) else None
    if 'model_auto_compact_token_limit' in config or window is None:
        # The user's own limit wins; without a known window there is no honest 35 percent.
        return rest
    block = f'{CODEX_COMPACT_START}\nmodel_auto_compact_token_limit = {window * COMPACT_PERCENT // 100}\n{CODEX_COMPACT_END}\n'
    # Top-level keys must precede the first table, so the block goes first.
    result = block + rest
    tomllib.loads(result)
    return result


def refuse_symlink(home, target, relative):
    if target.is_symlink() or any(p.is_symlink() for p in target.parents if p != home and p.is_relative_to(home)):
        raise ValueError(f'Refusing symlink target: {relative}')


def plan(home, source, runtimes=None):
    home, source = Path(home).resolve(), Path(source).resolve()
    src = oas if source == ROOT else load_oas(source)
    guidance = '\n\n'.join((source / f).read_text(encoding='utf-8') for f in src.SHARED_PROMPTS)
    guidance += '\n\n# Workflow selection\n\n'
    guidance += f'Workflows live in `{source}/workflows/`: development, research, ops, tutor, and unattended. Read only the one that fits the task, or the matching sections of each for a mixed request. Personal instructions outside this managed block and project instructions override these defaults. Do not auto-run an unattended job.\n'
    guidance += 'In Claude Code, each workflow is also the skill `oas-<mode>` (for example `oas-development`); load it through the Skill tool instead of reading the file.\n'
    changes = []
    def add(relative, content, executable=False):
        target = home / relative
        refuse_symlink(home, target, relative)
        before = target.read_bytes() if target.exists() else None
        after = content(before.decode('utf-8') if before is not None else '').encode('utf-8')
        if before != after:
            changes.append((target, before, after, executable))
    # OpenCode falls back to Claude's global instructions; preserve that personal
    # preamble when adding its own global file for the first time. Cursor needs
    # rule frontmatter when its file is new.
    old_claude = home / src.GLOBAL_INSTRUCTIONS['claude']
    fallbacks = {
        'opencode': old_claude.read_text(encoding='utf-8').split(START)[0] if old_claude.exists() else '',
        'cursor': '---\ndescription: Owen research, development, operations and learning defaults\nalwaysApply: true\n---\n',
    }
    for agent, relative in src.GLOBAL_INSTRUCTIONS.items():
        add(relative, lambda old, agent=agent: managed(old or fallbacks.get(agent, ''), guidance))
    for mode in src.MODES:
        body = '# Owen agent system profile\n' + '\n'.join(f'{k} = {src.toml_value(v)}' for k,v in src.flatten(src.config(mode))) + '\n'
        def profile(old, body=body):
            if old and not old.startswith('# Owen agent system profile\n'):
                raise ValueError('Refusing to replace an unmanaged Codex profile')
            return body
        add(f'.codex/owen-{mode}.config.toml', profile)
    for mode, description in WORKFLOW_SKILLS.items():
        def skill(old, text=workflow_skill(mode, source, description)):
            if old and WORKFLOW_SKILL_MARKER not in old:
                raise ValueError('Refusing to replace an unmanaged Claude skill')
            return text
        add(f'.claude/skills/oas-{mode}/SKILL.md', skill)
    if (home / '.codex/config.toml').is_file():
        add('.codex/config.toml', lambda old: codex_compaction(old, home))
    patches = {
        '.claude/settings.json': {'permissions': {'disableBypassPermissionsMode':'disable'},
                                  'env': {'CLAUDE_AUTOCOMPACT_PCT_OVERRIDE': str(COMPACT_PERCENT)}},
        '.gemini/settings.json': {'model': {'compressionThreshold': COMPACT_PERCENT / 100}},
        '.cursor/cli-config.json': {'sandbox': {'mode':'enabled'},'approvalMode':'allowlist'},
        '.config/opencode/opencode.json': {
            'permission':{'*':'ask','read':'allow','glob':'allow','grep':'allow','list':'allow','edit':'allow','external_directory':'ask','doom_loop':'ask'},
            'compaction':{'auto':True},
        },
    }
    # Claude Code (CLI and desktop app) and Codex inject a SessionStart hook's stdout
    # after every compaction, so the continuity reminder reaches sessions that the
    # oas launcher did not start. Codex asks the user to trust a new hook once.
    hook = compaction_hook(source)
    for relative in COMPACTION_HOOK_FILES:
        patches.setdefault(relative, {})
    for relative, patch in patches.items():
        def update(old, patch=patch, relative=relative):
            try:
                base = json.loads(old) if old.strip() else {}
                out = merged(base, patch)
            except ValueError as error:
                raise ValueError(f'Cannot update {relative}: {error}') from None
            if relative == '.claude/settings.json':
                out.setdefault('skillListingBudgetFraction', SKILL_LISTING_BUDGET)
            if relative in COMPACTION_HOOK_FILES:
                out = with_hook(out, hook)
            # Leave the file's own bytes alone when nothing changes: another writer's
            # formatting or raw UTF-8 is not a pending update.
            if old.strip() and out == base:
                return old
            return json.dumps(out, indent=2, ensure_ascii=False) + '\n'
        add(relative, update)
    # Remember explicit runtime choices across subsequent installer runs.
    wrapper_path = home / '.local/bin/oas'
    refuse_symlink(home, wrapper_path, '.local/bin/oas')
    selected = {}
    if wrapper_path.is_file():
        for line in wrapper_path.read_text(encoding='utf-8').splitlines():
            if line.startswith('# OAS runtimes: '):
                selected = json.loads(line.removeprefix('# OAS runtimes: '))
    if not isinstance(selected, dict):
        raise ValueError('Invalid OAS runtime selections in launcher')
    selected.update(runtimes or {})
    wrapper = '#!/bin/sh\n# Owen agent system launcher\n'
    if selected:
        wrapper += '# OAS runtimes: ' + json.dumps(selected, sort_keys=True) + '\n'
    for agent, value in sorted(selected.items()):
        if agent not in src.GLOBAL_INSTRUCTIONS or not isinstance(value, str):
            raise ValueError('Invalid OAS runtime selection')
        binary = Path(value).expanduser()
        if not binary.is_absolute() or not binary.is_file() or not os.access(binary, os.X_OK):
            raise ValueError(f'Runtime must be an absolute executable file: {agent}')
        variable = f'OAS_{agent.upper()}_BIN'
        wrapper += f'if [ -z "${{{variable}:-}}" ]; then export {variable}={shlex.quote(str(binary))}; fi\n'
    wrapper += 'exec ' + shlex.quote(sys.executable) + ' ' + shlex.quote(str(source / 'scripts/oas.py')) + ' "$@"\n'
    def launcher(old):
        if old and '# Owen agent system launcher\n' not in old:
            raise ValueError('Refusing to replace an unmanaged oas executable')
        return wrapper
    add('.local/bin/oas', launcher, True)
    return changes


def write_atomic(target, data, mode):
    temp = target.with_name(target.name + '.oas-' + uuid.uuid4().hex)
    try:
        with temp.open('xb') as f:
            os.chmod(temp, mode); f.write(data)
        os.replace(temp, target)
    finally:
        if temp.exists(): temp.unlink()


def matches_installed(target, digest, mode=None):
    """Older manifests have no installed mode; retain their byte-only comparison."""
    return (not target.is_symlink() and not any(p.is_symlink() for p in target.parents)
            and target.is_file() and (mode is None or stat.S_IMODE(target.stat().st_mode) == mode)
            and hashlib.sha256(target.read_bytes()).hexdigest() == digest)


def apply(changes, home):
    home = Path(home).resolve()
    for target, before, _, _ in changes:
        refuse_symlink(home, target, target.relative_to(home))
        if (target.read_bytes() if target.exists() else None) != before:
            raise ValueError(f'File changed since planning: {target.name}')
    if not changes:
        return None
    backup = home / '.local/state/owens-agent-system/backups' / (datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ') + '-' + uuid.uuid4().hex[:8])
    backup.mkdir(parents=True, mode=0o700)
    os.chmod(backup, 0o700)
    records = []
    for target, before, after, executable in changes:
        rel = target.relative_to(home)
        mode = stat.S_IMODE(target.stat().st_mode) if target.exists() else (0o755 if executable else 0o600)
        if before is not None:
            dest = backup / rel; dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(before); os.chmod(dest, 0o600)
        records.append(dict(path=str(rel), existed=before is not None, mode=mode,
                            installed_mode=0o755 if executable else mode,
                            installed_sha256=hashlib.sha256(after).hexdigest()))
    (backup / 'manifest.json').write_text(json.dumps(records, indent=2)+'\n', encoding='utf-8')
    done = []
    try:
        for (target,before,after,executable), record in zip(changes,records):
            refuse_symlink(home, target, target.relative_to(home))
            if (target.read_bytes() if target.exists() else None) != before:
                raise ValueError(f'Concurrent change: {target.name}')
            target.parent.mkdir(parents=True,exist_ok=True)
            write_atomic(target, after, record['installed_mode'])
            done.append((target,before,record))
    except Exception:
        for target,before,record in reversed(done):
            try:
                refuse_symlink(home, target, target.relative_to(home))
                if not matches_installed(target, record['installed_sha256'], record['installed_mode']):
                    print(f'Kept concurrent change during recovery: {target}', file=sys.stderr)
                    continue
                if before is None:
                    target.unlink()
                else:
                    write_atomic(target, before, record['mode'])
            except (OSError, ValueError) as error:
                # Recover other untouched writes without masking the install
                # failure or overwriting a concurrently replaced target.
                print(f'Could not recover {target}: {error}', file=sys.stderr)
        print(f'Installation failed. Recovery backup: {backup}', file=sys.stderr)
        raise
    return backup


def rollback_plan(home, backup):
    """Return (action, target, payload); restore payload is (bytes, mode, (installed digest, mode))."""
    home, backup = Path(home).resolve(), Path(backup).resolve()
    manifest = backup / 'manifest.json'
    if not manifest.is_file():
        raise ValueError(f'No manifest.json in backup directory: {backup}')
    actions = []
    for record in json.loads(manifest.read_text(encoding='utf-8')):
        rel = record['path']
        if not isinstance(rel, str) or not rel or Path(rel).is_absolute() or '..' in Path(rel).parts:
            raise ValueError(f'Manifest path must be relative and inside home: {rel!r}')
        target = home / rel
        refuse_symlink(home, target, rel)
        expected = (record['installed_sha256'], record.get('installed_mode'))
        if not target.exists():
            actions.append(('absent', target, None))
        elif not matches_installed(target, *expected):
            actions.append(('keep', target, None))
        elif record['existed']:
            saved = backup / rel
            if not saved.is_file():
                raise ValueError(f'Backup copy missing: {rel}')
            actions.append(('restore', target, (saved.read_bytes(), record['mode'], expected)))
        else:
            actions.append(('remove', target, expected))
    return actions


def rollback_apply(actions):
    """Execute a rollback plan. The backup directory is left in place. Returns counts per action."""
    counts = {action: 0 for action in LABELS}
    # Check the entire plan before making the first change, including restored files.
    for action, target, payload in actions:
        if action not in ('restore', 'remove'):
            continue
        if target.is_symlink() or any(p.is_symlink() for p in target.parents):
            raise ValueError(f'Refusing symlink target: {target}')
        expected = payload[2] if action == 'restore' else payload
        if not matches_installed(target, *expected):
            raise ValueError(f'File changed since planning: {target.name}')
    for action, target, payload in actions:
        if action == 'restore':
            data, mode, expected = payload
            if not matches_installed(target, *expected):
                raise ValueError(f'File changed since planning: {target.name}')
            target.parent.mkdir(parents=True, exist_ok=True)
            write_atomic(target, data, mode)
        elif action == 'remove':
            if not matches_installed(target, *payload):
                raise ValueError(f'File changed since planning: {target.name}')
            target.unlink()
        counts[action] += 1
    return counts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--home',type=Path,default=Path.home())
    parser.add_argument('--source',type=Path,default=ROOT)
    parser.add_argument('--apply',action='store_true')
    parser.add_argument('--codex-bin', help='Pin the OAS launcher to this installed Codex executable')
    parser.add_argument('--claude-bin', help='Pin the OAS launcher to this installed Claude executable')
    parser.add_argument('--rollback',type=Path,metavar='BACKUP_DIR',help='preview (or with --apply, perform) a rollback from this backup directory instead of installing')
    args=parser.parse_args()
    home=args.home.resolve()
    if args.rollback:
        actions=rollback_plan(home,args.rollback)
        for action,target,_ in actions: print(f'{LABELS[action]}: {target.relative_to(home)}')
        if args.apply:
            counts=rollback_apply(actions)
            print('Rolled back: ' + ', '.join(f'{n} {LABELS[a]}' for a,n in counts.items()) + '. Backup kept.')
        else:
            print(f'{len(actions)} records; preview only, re-run with --apply to roll back')
        return
    if args.apply and home == Path.home().resolve() and (args.source / '.git').is_file():
        parser.error('Install from the permanent checkout, not a linked worktree; use --source to select it')
    runtimes = {agent: value for agent, value in (('codex', args.codex_bin), ('claude', args.claude_bin)) if value}
    changes=plan(home,args.source,runtimes)
    for path,_,_,_ in changes: print(path.relative_to(home))
    print(f'{len(changes)} files to update')
    if args.apply:
        backup=apply(changes,home)
        print(f'Applied. Backup: {backup}' if backup else 'Already current.')

if __name__=='__main__':
    try:
        main()
    except ValueError as error:
        # A refusal is an expected outcome; print it without a traceback.
        print(f'ERROR: {error}', file=sys.stderr)
        sys.exit(2)
